/**
 * 从实体元数据生成 PostgreSQL DDL，产出仓库内的 {@code sql/schema-postgres.sql}。
 *
 * <p><b>为什么用测试来生成。</b>Hibernate 7 已移除 {@code org.hibernate.tool.hbm2ddl.SchemaExport}，
 * 官方路径只剩 {@code SchemaManagementToolCoordinator} 配合 JPA 的
 * {@code jakarta.persistence.schema-generation.*} 属性。而实体清单由 Spring Boot 的
 * {@code @SpringBootApplication} 包扫描给出，因此走一次真实的上下文启动，
 * 新增实体会被自动纳入，不会出现「加了实体却忘了加进生成器」的漏项。
 *
 * <p><b>连接用 H2、方言用 PostgreSQL。</b>脚本生成只读元数据，不需要连到 PostgreSQL，
 * 这样生成过程不依赖数据库可用性。但方言必须显式钉住 PostgreSQL 16（Hibernate 7.4
 * 默认目标），见 {@link PostgresDialectResolver}——否则 Hibernate 会把 H2 上报的版本号
 * 当成目标版本，按 H2 的路径生成 DDL。
 *
 * <p><b>与 MySQL 脚本的关键差异。</b>MySQL 把注释写进 {@code create table} 行内
 * （{@code comment='...'}），而 PostgreSQL 方言会输出<b>独立的</b>
 * {@code comment on table X is '...'} / {@code comment on column X.Y is '...'} 语句；
 * 自增列在 PostgreSQL 上是 {@code generated by default as identity} 而非
 * {@code auto_increment}；没有 {@code engine=InnoDB}、没有 {@code unsigned}、
 * 没有 {@code mediumtext}。因此本测试的注释断言改为解析独立的 {@code comment on} 语句。
 *
 * <p><b>MySQL 专有的行大小上限测试在本方言不适用。</b>MySQL 的 65535 字节行上限是
 * InnoDB 存储层的硬约束，对应测试见 {@code MysqlDdlGeneratorTests}；PostgreSQL 走
 * TOAST，大文本列不会撑爆行，故不在此重复这条断言。
 *
 * <p>数据源相关属性在这里全部显式给出，不使用 {@code application.yml} 的默认值——
 * 默认值已经指向 MySQL，若沿用会让本测试要求一个真实数据库才能跑。
 */
@SpringBootTest(properties = {
        // 生成脚本只需要元数据，不连真实库；用 H2 保证任何环境都能执行
        "spring.datasource.url=jdbc:h2:mem:ddlgen;DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        // 不设 spring.jpa.database-platform：改由下面的 DialectResolver 决定方言，
        // 这样方言版本可控，也不会触发 HHH90000025（不该显式指定 hibernate.dialect）
        "spring.jpa.properties.hibernate.dialect_resolvers="
                + "io.github.melin.lakehouse.rest.PostgresDdlGeneratorTests$PostgresDialectResolver",
        // 关掉自动建表，只写脚本
        "spring.jpa.hibernate.ddl-auto=none",
        // hibernate.format_sql 除了美化日志里的 SQL，也决定 DDL 脚本是否换行缩进。
        // 不打开的话每条 create table 会挤成一整行（最长近 3000 字符），无法审阅与 diff。
        "spring.jpa.properties.hibernate.format_sql=true",
        "spring.jpa.properties.jakarta.persistence.schema-generation.scripts.action=create",
        "spring.jpa.properties.jakarta.persistence.schema-generation.create-source=metadata",
        // 每次覆盖而不是追加，保证脚本可重复生成
        "spring.jpa.properties.hibernate.hbm2ddl.schema-generation.script.append=false",
        // 关掉启动期预置数据：此时库里没有表，预置会失败
        "lakehouse.rest.initial-catalog.prefix=",
        // 同上：内置敏感类型的 seed 也是一个「启动后查库」的 ApplicationRunner，
        // 而这里刻意 ddl-auto=none（只生成脚本、不建真表），
        // lakehouse_sensitive_type 根本不存在，seed 会在启动阶段抛
        // 「Table "LAKEHOUSE_SENSITIVE_TYPE" not found」。
        // 关掉而不是给它加 try/catch：本测试的意图是「JPA 元数据 → DDL 文本」，
        // 它不该因为「库里有没有表」而变绿或变红；吞异常的 catch 会把
        // 「表真的没建出来」这个事实一起藏起来。
        "lakehouse.rest.sensitivity.seed-builtin-types=false",
        "lakehouse.rest.authorization.enabled=false",
        "lakehouse.rest.auth.enabled=false"
})
class PostgresDdlGeneratorTests {

    /**
     * 把方言钉到 PostgreSQL 16。
     *
     * <p><b>为什么需要它。</b>若只写 {@code hibernate.dialect=PostgreSQLDialect}，
     * Hibernate 会用 {@code PostgreSQLDialect(DialectResolutionInfo)} 构造方言，
     * 而这里的连接是 H2，于是它把 H2 上报的 {@code 2.4.240} 当成目标版本，
     * 输出 {@code HHH000511: The 2.4.240 version for PostgreSQLDialect is no longer supported}，
     * 并可能按 PostgreSQL 2.x 的旧路径生成 DDL。DDL 的目标版本必须是确定的，
     * 所以这里显式返回 16。
     *
     * <p>必须是 public static 且有无参构造函数，{@code hibernate.dialect_resolvers}
     * 按类名实例化它。
     */
    public static class PostgresDialectResolver implements DialectResolver {

        @Override
        public Dialect resolveDialect(DialectResolutionInfo info) {
            return new PostgreSQLDialect(DatabaseVersion.make(16, 0));
        }
    }

    /**
     * 脚本输出位置。
     *
     * <p>默认写到 {@code target/}（构建产物，不入仓库）；
     * {@code scripts/gen-postgres-ddl.sh} 通过 {@code -Dpostgres.ddl.output=...} 指到交付路径。
     */
    private static final Path OUTPUT = Path.of(
            System.getProperty("postgres.ddl.output", "target/postgres-schema.sql"))
            .toAbsolutePath();

    /**
     * 实体的表数量；新增/删除实体时应同步调整，否则本测试会失败提醒。
     *
     * <p>与 MySQL 脚本共用同一套实体，因此数量同为 36（见
     * {@code MysqlDdlGeneratorTests#EXPECTED_TABLES} 的演进注释：从 23 经行过滤/列脱敏
     * 到 25，加 catalog 级执行集群到 26，加调度通道租约到 27，加 Lance 版本账到 28，
     * 加身份接入的组映射表到 29，加敏感数据识别五张表到 34，加 P1 人审的抑制项表到 35，
     * 加 P4 自建调度的调度项表到 36）。
     *
     * <p><b>两个测试各写一份常量，是刻意的。</b>它们各自加载**不同方言**的上下文
     * （{@code MySql8Dialect} / {@code PostgreSQLDialect}），一份变了另一份没变时，
     * 失败会同时落在两个类上——这比让一个类去 import 另一个类的常量更能说明「方言
     * 无关的表数事实被两处都读到了」。两份不一致时先看这里与 MySQL 那份的差值。
     */
    private static final int EXPECTED_TABLES = 36;

    /** 表级注释：{@code comment on table X is '...'}。 */
    private static final Pattern TABLE_COMMENT = Pattern.compile(
            "comment\\s+on\\s+table\\s+(\\w+)\\s+is\\s+'(?:[^']|'')*'",
            Pattern.CASE_INSENSITIVE);

    /** 列级注释：{@code comment on column X.Y is '...'}。 */
    private static final Pattern COLUMN_COMMENT = Pattern.compile(
            "comment\\s+on\\s+column\\s+(\\w+)\\.(\\w+)\\s+is\\s+'(?:[^']|'')*'",
            Pattern.CASE_INSENSITIVE);

    @Autowired
    private EntityManagerFactory entityManagerFactory;

    @DynamicPropertySource
    static void schemaGenerationProperties(DynamicPropertyRegistry registry) {
        registry.add("spring.jpa.properties.jakarta.persistence.schema-generation.scripts.create-target",
                () -> OUTPUT.toString());
    }

    @Test
    void generatesPostgresDdlForEveryEntity() throws IOException {
        assertTrue(Files.exists(OUTPUT), "未生成 DDL 脚本：" + OUTPUT);
        String ddl = Files.readString(OUTPUT, StandardCharsets.UTF_8);

        Matcher tables = Pattern.compile("(?im)^\\s*create table\\s+", Pattern.MULTILINE).matcher(ddl);
        int count = 0;
        while (tables.find()) {
            count++;
        }
        assertEquals(EXPECTED_TABLES, count,
                "DDL 中的建表语句数量与实体数量不符，说明有实体未被扫描到或已被删除：" + OUTPUT);

        // 方言必须真的生效：自增列应为 identity，文本列应为 text（PostgreSQL 没有 mediumtext）
        String lower = ddl.toLowerCase(Locale.ROOT);
        assertTrue(lower.contains("identity"),
                "生成的 DDL 不是 PostgreSQL 方言（自增列应为 identity）：" + OUTPUT);
        assertTrue(lower.contains("text"),
                "生成的 DDL 不是 PostgreSQL 方言（文本列应为 text）：" + OUTPUT);
        // 反向确认：绝不能残留 MySQL 方言产物
        assertFalse(lower.contains("engine=innodb"),
                "生成的 DDL 混入了 MySQL 方言（engine=innodb）：" + OUTPUT);
        assertFalse(lower.contains("auto_increment"),
                "生成的 DDL 混入了 MySQL 方言（auto_increment）：" + OUTPUT);
        assertFalse(lower.contains("mediumtext"),
                "生成的 DDL 混入了 MySQL 方言（mediumtext）：" + OUTPUT);
    }

    /**
     * 每张表、每一列都必须带注释。
     *
     * <p><b>为什么这条要当成断言。</b>注释来自实体的 {@code @Table(comment = ...)} /
     * {@code @Column(comment = ...)}，是这份 DDL 里唯一由人写给读者看的东西：库里
     * 没有注释的表就是「一串看不出用途的列」，而排查线上数据问题的第一步往往就是看表注释。
     * PostgreSQL 把注释输出成独立的 {@code comment on} 语句，因此这里解析这些语句，
     * 再与建表语句里出现的（表、列）清单做交叉核对。
     *
     * <p>约束子句（{@code primary key} 等）不是列，按 {@link #isConstraintClause} 排除；
     * 它们不会有注释，也不应计入「列必须有注释」的校验。
     */
    @Test
    void everyTableAndColumnIsCommented() throws IOException {
        String ddl = Files.readString(OUTPUT, StandardCharsets.UTF_8);

        Set<String> commentedTables = new HashSet<>();
        Matcher tc = TABLE_COMMENT.matcher(ddl);
        while (tc.find()) {
            commentedTables.add(tc.group(1).toLowerCase(Locale.ROOT));
        }

        Set<String> commentedColumns = new HashSet<>();
        Matcher cc = COLUMN_COMMENT.matcher(ddl);
        while (cc.find()) {
            commentedColumns.add((cc.group(1) + "." + cc.group(2)).toLowerCase(Locale.ROOT));
        }

        List<String> tablesWithoutComment = new ArrayList<>();
        List<String> columnsWithoutComment = new ArrayList<>();
        for (TableBlock table : extractTables(ddl)) {
            String tableName = table.name().toLowerCase(Locale.ROOT);
            if (!commentedTables.contains(tableName)) {
                tablesWithoutComment.add(table.name());
            }
            for (String column : table.columns()) {
                String key = tableName + "." + column.toLowerCase(Locale.ROOT);
                if (!commentedColumns.contains(key)) {
                    columnsWithoutComment.add(table.name() + "." + column);
                }
            }
        }

        assertTrue(!tablesWithoutComment.isEmpty() || !commentedTables.isEmpty(),
                "没解析到任何建表语句或注释语句，断言会变成空转：" + OUTPUT);
        assertTrue(tablesWithoutComment.isEmpty(),
                "下列表没有注释，请在实体的 @Table 上补 comment：" + tablesWithoutComment);
        assertTrue(columnsWithoutComment.isEmpty(),
                "下列列没有注释，请在实体的 @Column 上补 comment：" + columnsWithoutComment);
    }

    /**
     * 锁住方言版本。
     *
     * <p>这条断言防的是「方言退化成按 H2 上报的版本号解释」：一旦解除
     * {@link PostgresDialectResolver}，Hibernate 会把 H2 的 {@code 2.4.240} 当成
     * PostgreSQL 版本，生成的 DDL 就按旧版本路径走。建表语句数量之类的断言不会发现
     * 这种偏移，必须直接查版本。
     */
    @Test
    void pinsTheDialectToPostgres16() {
        Dialect dialect = entityManagerFactory.unwrap(SessionFactoryImplementor.class)
                .getJdbcServices()
                .getDialect();
        assertInstanceOf(PostgreSQLDialect.class, dialect, "方言不是 PostgreSQLDialect");
        assertEquals(16, dialect.getVersion().getMajor(), "方言主版本不是 16（可能被 H2 的版本号污染）");
        assertEquals(0, dialect.getVersion().getMinor(), "方言次版本不是 0");
    }

    /**
     * 表内的约束子句不是列定义，别把 {@code primary key (id)} 当成一个叫 primary 的列。
     *
     * <p>按行首关键字排除而不是「认不出就跳过」：列名一旦被引号包起来就不再命中这些前缀，
     * 能正常计入。
     */
    private static boolean isConstraintClause(String definition) {
        String lower = definition.toLowerCase(Locale.ROOT);
        return lower.startsWith("primary key")
                || lower.startsWith("foreign key")
                || lower.startsWith("unique ")
                || lower.startsWith("constraint ")
                || lower.startsWith("check ")
                || lower.startsWith("key ")
                || lower.startsWith("index ");
    }

    /**
     * 解析出每个 {@code create table} 的表名与其列名清单。
     *
     * <p>用括号配平截取建表体：列类型里的 {@code varchar(64)}、约束里的
     * {@code primary key (id)} 都是平衡的，因此第一个回到 0 的右括号就是表级结尾。
     * 列名取每行的第一个空白分隔 token；约束子句与空行按 {@link #isConstraintClause} 排除。
     */
    private static List<TableBlock> extractTables(String ddl) {
        List<TableBlock> result = new ArrayList<>();
        Matcher head = Pattern.compile("(?i)create table\\s+(\\w+)").matcher(ddl);
        while (head.find()) {
            String name = head.group(1);
            int open = ddl.indexOf('(', head.end());
            if (open < 0) {
                continue;
            }
            int depth = 0;
            int end = open;
            for (int i = open; i < ddl.length(); i++) {
                char ch = ddl.charAt(i);
                if (ch == '(') {
                    depth++;
                } else if (ch == ')') {
                    depth--;
                    if (depth == 0) {
                        end = i;
                        break;
                    }
                }
            }
            String body = ddl.substring(open + 1, end);
            List<String> columns = new ArrayList<>();
            for (String raw : body.split("\n")) {
                String definition = raw.strip();
                if (definition.endsWith(",")) {
                    definition = definition.substring(0, definition.length() - 1).strip();
                }
                if (definition.isEmpty() || isConstraintClause(definition)) {
                    continue;
                }
                String column = definition.split("\\s+")[0]
                        .replace("`", "").replace("\"", "");
                if (!column.isEmpty()) {
                    columns.add(column);
                }
            }
            result.add(new TableBlock(name, columns));
        }
        return result;
    }

    /** 一张表的名字与其列名清单。 */
    private record TableBlock(String name, List<String> columns) {
    }
}
